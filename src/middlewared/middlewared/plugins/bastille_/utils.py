def atomic_write(path, content, mode=0o600):
    directory = os.path.dirname(path)
    os.makedirs(directory, mode=0o750, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix='.middlewared-', dir=directory)
    try:
        with os.fdopen(descriptor, 'w') as file:
            file.write(content)
            file.flush()
            os.fsync(file.fileno())
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def _render_config_stop(message, indent):
    """Shell that ends an unaided `bastille` with `message`, unless it was asked for help.

    bastille sources this file before it reads its own options, so its help and
    version, and -c naming another config file, are let through: they never use
    the defaults this stop exists to keep bastille away from.
    """
    return (
        f'{indent}case "${{1}}" in\n'
        f'{indent}-h|--help|help|-v|--version|version|-c|--config) ;;\n'
        f'{indent}*)\n'
        f"{indent}    echo 'bastille: {message}' >&2\n"
        f'{indent}    exit 1\n'
        f'{indent}    ;;\n'
        f'{indent}esac\n'
    )


def render_config_pointer(pool):
    """Render the managed block: include the pool's configuration, or stop `bastille`.

    the internal development record: without a pool to include, bastille ran on the stock
    defaults left in this file -- ZFS off and a prefix under /usr/local, which on
    this appliance is the boot environment -- and its bootstrap offered to continue
    there. A `y` put the release, and then its jails, in the boot environment's root
    on the boot pool. So the block now stops bastille instead, with the reason:
    no pool configured, or the configured pool's file is missing because the pool
    is exported, locked or offline. A file that exists but cannot be read means a
    non-root caller, and bastille's own root check reports that.
    """
    if pool is None:
        return (
            f'{CONFIG_POINTER_BEGIN}\n'
            '# Written by middlewared. No Bastille data pool is configured; choose one in\n'
            '# the web interface. Until then bastille stops here rather than run on the\n'
            '# defaults in this file, which keep releases and jails on the boot pool.\n'
            + _render_config_stop(
                'no Bastille data pool is configured. Choose one in the web interface: '
                'Jails > Bastille Jails > Bastille Settings.',
                '',
            )
            + f'{CONFIG_POINTER_END}\n'
        )
    config_file = bastille_paths(pool)['config_file']
    return (
        f'{CONFIG_POINTER_BEGIN}\n'
        '# Written by middlewared. Edit the Bastille data pool in the web interface.\n'
        '# bastille sources this file, so the pool configuration is included rather than\n'
        '# copied: there is still exactly one place to change a setting. While the pool\n'
        '# is exported, locked or offline, bastille stops here rather than run on the\n'
        '# defaults in this file, which keep releases and jails on the boot pool.\n'
        f'if [ -r {config_file} ]; then\n'
        f'    . {config_file}\n'
        f'elif [ ! -e {config_file} ]; then\n'
        + _render_config_stop(
            f'the Bastille data pool {pool} is not available (exported, locked or offline).',
            '    ',
        )
        + 'fi\n'
        f'{CONFIG_POINTER_END}\n'
    )


def _split_config_pointer(content):
    """Split `content` into the lines outside every managed block and where the first began.

    An unbalanced marker pair is refused rather than guessed at: rewriting a file we
    cannot parse could silently discard hand-written settings.
    """
    kept = []
    insert_at = None
    inside = False
    for line in content.splitlines(keepends=True):
        marker = line.strip()
        if marker == CONFIG_POINTER_BEGIN:
            if inside:
                raise CallError(
                    f'{BASTILLE_DEFAULT_CONFIG} has a nested FreeCORE managed block.'
                )
            inside = True
            if insert_at is None:
                insert_at = len(kept)
            continue
        if marker == CONFIG_POINTER_END:
            if not inside:
                raise CallError(
                    f'{BASTILLE_DEFAULT_CONFIG} ends a FreeCORE managed block that never began.'
                )
            inside = False
            continue
        if not inside:
            kept.append(line)
    if inside:
        raise CallError(
            f'{BASTILLE_DEFAULT_CONFIG} has an unterminated FreeCORE managed block.'
        )
    return kept, insert_at


def strip_config_pointer(content):
    """Return `content` without any managed block: the administrator's lines alone."""
    return ''.join(_split_config_pointer(content)[0])


def apply_config_pointer(content, pool):
    """Return `content` carrying exactly one managed block, for `pool` or for no pool.

    Everything outside the markers is preserved byte for byte, because this file
    belongs to the administrator. Repeated application is a no-op, and any duplicate
    blocks left by an earlier write collapse into one.
    """
    kept, insert_at = _split_config_pointer(content)
    block = render_config_pointer(pool)
    if insert_at is None:
        # Keep a hand-written last line intact if it had no trailing newline.
        if kept and not kept[-1].endswith('\n'):
            kept[-1] += '\n'
        kept.append(block)
    else:
        # Rewrite in place, so an administrator who moved the block keeps it there.
        kept.insert(insert_at, block)
    return ''.join(kept)


def read_cli_config_source():
    """The file the CLI pointer is applied to: the live bastille.conf, else the sample.

    Returns None when neither exists (bastille is not installed, or the package
    directory is gone), so the caller can leave nothing behind. A live file that is
    not a plain regular file, or is implausibly large, is refused rather than
    rewritten: the internal development record owns one block of the administrator's file,
    never the file.
    """
    for path in (BASTILLE_DEFAULT_CONFIG, BASTILLE_SAMPLE_CONFIG):
        try:
            metadata = os.lstat(path)
        except FileNotFoundError:
            continue
        except OSError as error:
            raise CallError(f'Unable to inspect {path!r}: {error}')
        if not stat.S_ISREG(metadata.st_mode):
            raise CallError(f'{path} is not a regular file; refusing to rewrite it.')
        if metadata.st_size > MAX_CLI_CONFIG_SIZE:
            raise CallError(f'{path} is too large to manage safely.')
        try:
            return Path(path).read_text(encoding='utf8')
        except (OSError, UnicodeDecodeError) as error:
            raise CallError(f'Unable to read {path!r}: {error}')
    return None
