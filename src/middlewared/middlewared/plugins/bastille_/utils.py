# delimited block inside it. See the internal development record.
BASTILLE_DEFAULT_CONFIG = '/usr/local/etc/bastille/bastille.conf'
# /etc is a tmpfs seeded from /conf/base/etc at boot and /usr/local/etc is /etc/local, so
