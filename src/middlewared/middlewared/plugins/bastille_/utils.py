def bastille_paths(pool):
    if not isinstance(pool, str) or not POOL_NAME.fullmatch(pool):
        raise ValueError('Bastille pool name is invalid.')

    dataset = f'{pool}/bastille'
    mountpoint = f'/mnt/{dataset}'
    logical_prefix = f'/{dataset}'
    return {
        'dataset': dataset,
        'mountpoint': mountpoint,
        'logical_prefix': logical_prefix,
        'backups_dataset': f'{dataset}/backups',
        'backups': f'{mountpoint}/backups',
        'cache_dataset': f'{dataset}/cache',
        'cache': f'{mountpoint}/cache',
        'config_dataset': f'{dataset}/config',
        'config': f'{mountpoint}/config',
        'config_file': f'{mountpoint}/config/bastille.conf',
        'pf_config': f'{mountpoint}/config/pf.conf',
        'monitor_cron': f'{mountpoint}/config/bastille-monitor.cron',
        'jails_dataset': f'{dataset}/jails',
        'jails': f'{mountpoint}/jails',
        'logs_dataset': f'{dataset}/logs',
        'logs': f'{mountpoint}/logs',
        'releases_dataset': f'{dataset}/releases',
        'releases': f'{mountpoint}/releases',
        'templates_dataset': f'{dataset}/templates',
        'templates': f'{mountpoint}/templates',
    }


