import contextlib
import ipaddress
import os
import re
import subprocess
import tempfile

from middlewared.plugins.applications_.utils import RUNTIME_PF_ACTIVE
from middlewared.service_exception import CallError

PF_BLOCK_FILE = '/etc/pf.conf.block'
PFCTL = '/sbin/pfctl'
INTERFACE_NAME = re.compile(r'^[A-Za-z0-9_.:-]+$')


def _applications_config(middleware):
    return middleware.call_sync('applications.config')


def _egress_interfaces(middleware):
    interfaces = {}
    for route in middleware.call_sync(
        'route.system_routes', [('netmask', 'in', ['0.0.0.0', '::'])]
    ):
        interface = route.get('interface')
        if not interface or not INTERFACE_NAME.match(interface):
            continue
        try:
            family = ipaddress.ip_address(route['gateway'].split('%', 1)[0]).version
        except (KeyError, ValueError):
            continue
        interfaces.setdefault(family, interface)
    return interfaces


def _application_rules(middleware):
    interfaces = _egress_interfaces(middleware)
    if 4 not in interfaces:
        raise CallError('Applications requires an IPv4 default-route interface for CNI NAT.')

    rules = []
    if 4 in interfaces:
        rules.append(f'v4egress_if = "{interfaces[4]}"')
    if 6 in interfaces:
        rules.append(f'v6egress_if = "{interfaces[6]}"')
    rules.extend(['', 'table <cni-nat>'])
    if 4 in interfaces:
        rules.append('nat on $v4egress_if inet from <cni-nat> to any -> ($v4egress_if)')
    if 6 in interfaces:
        rules.append(
            'nat on $v6egress_if inet6 from <cni-nat> to !ff00::/8 -> ($v6egress_if)'
        )
    rules.extend([
        'rdr-anchor "cni-rdr/*"',
        'nat-anchor "cni-rdr/*"',
    ])
    return rules


def _failover_rules(middleware):
    interfaces = middleware.call_sync('interface.query')
    ips = []
    for interface in interfaces:
        for alias in interface['failover_virtual_aliases']:
            try:
                ips.append(str(ipaddress.ip_address(alias['address'])))
            except (KeyError, ValueError):
                continue
    if not ips:
        ips = ['0.0.0.0']

    ssh = middleware.call_sync('ssh.config')
    general = middleware.call_sync('system.general.config')
    ports = [ssh['tcpport'], general['ui_port'], general['ui_httpsport']]
    return [
        '',
        f"ips = '{{ {', '.join(ips)} }}'",
        f"ports = '{{ {', '.join(map(str, ports))} }}'",
        'pass in quick proto tcp from any to any port $ports',
        'block drop in quick proto tcp from any to $ips',
        'block drop in quick proto udp from any to $ips',
    ]


def build_rules(middleware, applications, failover):
    rules = ['# Generated by middlewared. Do not edit.', 'set block-policy drop']
    if applications:
        rules.extend(['', '# Native Applications CNI translation', *_application_rules(middleware)])
    if failover:
        rules.extend(['', '# Failover management-access protection', *_failover_rules(middleware)])
    return '\n'.join(rules) + '\n'


def _write_temporary(content):
    directory = os.path.dirname(PF_BLOCK_FILE)
    prefix = f'.{os.path.basename(PF_BLOCK_FILE)}-'
    descriptor, path = tempfile.mkstemp(prefix=prefix, dir=directory)
    try:
        with os.fdopen(descriptor, 'w') as file:
            file.write(content)
            file.flush()
            os.fsync(file.fileno())
        os.chmod(path, 0o600)
        return path
    except Exception:
        try:
            os.unlink(path)
        except FileNotFoundError:
            pass
        raise


def _run_pfctl(*arguments):
    try:
        return subprocess.run(
            [PFCTL, *arguments],
            check=False,
            text=True,
            capture_output=True,
            timeout=30,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise CallError(f'Unable to execute PF operation {arguments!r}: {error}')


def _restore_file(previous):
    if previous is None:
        try:
            os.unlink(PF_BLOCK_FILE)
        except FileNotFoundError:
            pass
        return
    replacement = _write_temporary(previous)
    os.replace(replacement, PF_BLOCK_FILE)


def _result_error(result):
    return (result.stderr or result.stdout or '').strip()


def _rollback(previous):
    try:
        _restore_file(previous)
    except OSError as error:
        return f'unable to restore prior rules file: {error}'

    if previous is None:
        return 'no prior rules file was available to reload'
    try:
        result = _run_pfctl('-f', PF_BLOCK_FILE)
    except CallError as error:
        return str(error)
    if result.returncode:
        return _result_error(result) or 'pfctl returned an error'
    return None


def _raise_after_rollback(message, previous):
    rollback_error = _rollback(previous)
    if rollback_error:
        raise CallError(f'{message}; rollback also failed: {rollback_error}.')
    raise CallError(f'{message}; previous rules were restored.')


def _load_rules(content, enable):
    previous = None
    if os.path.exists(PF_BLOCK_FILE):
        with open(PF_BLOCK_FILE) as file:
            previous = file.read()

    candidate = _write_temporary(content)
    try:
        validation = _run_pfctl('-n', '-f', candidate)
    except CallError:
        with contextlib.suppress(FileNotFoundError):
            os.unlink(candidate)
        raise
    if validation.returncode:
        os.unlink(candidate)
        raise CallError(f'Generated PF rules failed validation: {_result_error(validation)}')

    os.replace(candidate, PF_BLOCK_FILE)
    try:
        loaded = _run_pfctl('-f', PF_BLOCK_FILE)
    except CallError as error:
        _raise_after_rollback(str(error), previous)
    if loaded.returncode:
        _raise_after_rollback(f'PF load failed: {_result_error(loaded)}', previous)

    if enable:
        try:
            status = _run_pfctl('-s', 'info')
        except CallError as error:
            _raise_after_rollback(str(error), previous)
        if status.returncode or 'Status: Enabled' not in status.stdout:
            try:
                enabled = _run_pfctl('-e')
            except CallError as error:
                _raise_after_rollback(str(error), previous)
            if enabled.returncode and 'already enabled' not in enabled.stderr.lower():
                _raise_after_rollback(f'Unable to enable PF: {_result_error(enabled)}', previous)


def render(service, middleware):
    applications = bool(
        _applications_config(middleware)['pool'] and os.path.exists(RUNTIME_PF_ACTIVE)
    )
    failover = middleware.call_sync('failover.licensed')

    if not applications and not failover:
        try:
            os.unlink(PF_BLOCK_FILE)
        except FileNotFoundError:
            pass
        return

    _load_rules(build_rules(middleware, applications, failover), applications)
